/**
 * Dashboard pieces that need real PostgreSQL: the V6 constraint, the bulk queries, and
 * one end-to-end coordinator dashboard. Needs ojttrack_test (application-dbtest.properties).
 * Run from backend/:  .\mvnw.cmd test "-Dtest=*DbTest"  (with DB_PASSWORD set)
 */
@DataJpaTest
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@ActiveProfiles("dbtest")
@Import({DashboardService.class, TimeConfig.class})
class DashboardDbTest {

    @Autowired AppUserRepository users;
    @Autowired JobApplicationRepository applications;
    @Autowired PlacementRepository placements;
    @Autowired TimeLogRepository logs;
    @Autowired DashboardService service;
    @Autowired EntityManager em;

    AppUser coordinator;
    AppUser placed;
    AppUser searching;

    @BeforeEach
    void setUp() {
        coordinator = users.save(AppUser.coordinator("dash-coord@test.local", "hash", "Dash Coordinator"));
        placed = users.save(AppUser.student("dash-s1@test.local", "hash", "Alice Placed", coordinator.getId()));
        searching = AppUser.student("dash-s2@test.local", "hash", "Bob Searching", coordinator.getId());
        searching.setPlacementSearchStartsOn(LocalDate.of(2020, 1, 1));   // long past: expected to be searching
        searching = users.save(searching);
    }

    @Test
    void coordinatorsCannotHaveASearchStartDate() {
        assertThatThrownBy(() -> em.createNativeQuery(
                "UPDATE users SET placement_search_starts_on = DATE '2027-01-01' WHERE id = " + coordinator.getId())
                .executeUpdate())
                .hasStackTraceContaining("chk_users_search_start_students_only");
    }

    @Test
    void bulkQueriesReturnOnlyTheRequestedRows() {
        Placement placement = activePlacement(placed, "Acme");
        logs.saveAndFlush(TimeLog.submit(placement.getId(), placed.getId(), LocalDate.of(2020, 1, 6),
                LocalTime.of(8, 0), LocalTime.of(17, 0), false, 60, "work"));

        assertThat(placements.findByStudentIdIn(List.of(placed.getId(), searching.getId())))
                .extracting(Placement::getId).containsExactly(placement.getId());
        assertThat(logs.findByPlacementIdIn(List.of(placement.getId()))).hasSize(1);
        assertThat(logs.findByPlacementIdIn(List.of(-1))).isEmpty();
    }

    @Test
    void coordinatorDashboardEndToEnd() {
        Placement placement = activePlacement(placed, "Acme");
        TimeLog pending = logs.saveAndFlush(TimeLog.submit(placement.getId(), placed.getId(), LocalDate.of(2020, 1, 6),
                LocalTime.of(8, 0), LocalTime.of(17, 0), false, 60, "work"));
        em.flush();
        em.clear();

        CoordinatorDashboardResponse dashboard = service.coordinatorDashboard(coordinator.getId());

        assertThat(dashboard.totals().students()).isEqualTo(2);
        assertThat(dashboard.totals().activePlacements()).isEqualTo(1);
        assertThat(dashboard.totals().logsAwaitingReview()).isEqualTo(1);
        // Both are flagged: Bob has no placement (search started 2020); Alice's last log was in 2020.
        assertThat(dashboard.students()).allSatisfy(row -> assertThat(row.flags()).isNotEmpty());
        CoordinatorDashboardResponse.StudentRow alice = dashboard.students().stream()
                .filter(r -> r.studentId().equals(placed.getId())).findFirst().orElseThrow();
        assertThat(alice.placement().companyName()).isEqualTo("Acme");
        assertThat(alice.placement().progress().pendingMinutes()).isEqualTo(480);   // generated by PostgreSQL
        assertThat(alice.flags()).extracting(AssistanceFlag::code).containsExactly(AssistanceFlag.Code.NO_RECENT_LOGS);
        assertThat(pending.getId()).isNotNull();
    }

    private Placement activePlacement(AppUser student, String company) {
        JobApplication app = BeanUtils.instantiateClass(JobApplication.class);
        app.setStudentId(student.getId());
        app.setCompanyName(company);
        app.setStatus(ApplicationStatus.ACCEPTED);
        applications.saveAndFlush(app);
        return placements.saveAndFlush(Placement.activate(app.getId(), student.getId(),
                LocalDate.of(2020, 1, 6), LocalDate.of(2020, 6, 30), 486));
    }
}
